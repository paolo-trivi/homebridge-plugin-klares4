/** 2.2.0 returned "light" from its last line for any category it did not match. */
const reachedByDefault = (category, type) => type === 'light' && category.toUpperCase() !== 'LIGHT';

test('COMMS-08: every output 2.2.0 exposed keeps its type and ID, or is hidden by the fail-closed policy', () => {
    let kept = 0;
    let hidden = 0;
    V220.forEach(([CAT, MOD, type220], index) => {
        const output = { ID: String(100 + index), DES: 'x', CAT, ...(MOD === null ? {} : { MOD }) };
        const label = `CAT=${JSON.stringify(CAT)} MOD=${JSON.stringify(MOD)}`;
        const exposure = resolveOutputExposure(output, new Map(), new OutputTypeMemory());
        if (!exposure.exposed) {
            assert.ok(reachedByDefault(CAT, type220), `${label}: 2.2.0 recognized it as ${type220}, it must stay exposed`);
            hidden += 1;
            return;
        }
        assert.equal(exposure.type, type220, label);
        assert.equal(parseOutputData(output).id, `${type220}_${output.ID}`, label);
        kept += 1;
    });
    assert.ok(kept > 0 && hidden > 0);
});

test('COMMS-08: an output re-exposed with exposeOutputs gets the ID 2.2.0 gave it', () => {
    V220.filter(([CAT, , type]) => reachedByDefault(CAT, type)).forEach(([CAT, MOD], index) => {
        const output = { ID: String(900 + index), DES: 'x', CAT, ...(MOD === null ? {} : { MOD }) };
        const exposure = resolveOutputExposure(output, new Map([[output.ID, 'light']]), new OutputTypeMemory());
        assert.equal(exposure.exposed, true);
        assert.equal(parseOutputData(output).id, `light_${output.ID}`);
    });
});
